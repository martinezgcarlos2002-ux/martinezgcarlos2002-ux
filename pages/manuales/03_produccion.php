  <h1>3. Producción e inventario</h1>
  <p>La leche recibida se transforma en queso. ADARA separa lo que entró, lo que se fabricó y lo que se perdió, para que el inventario coincida con la planta.</p>

  <h2>Del litro al queso</h2>
  <p>En <strong>Producción</strong> se registra el día de trabajo: la leche usada y los kilos obtenidos de cada tipo. La quesera trabaja, entre otros, queso guayanés, telita, mozzarella y arepero. Cada producto del catálogo de producción tiene su unidad y su rendimiento de referencia.</p>
  <ol>
    <li>Elija la fecha del día de producción.</li>
    <li>Indique la leche consumida y los kilos de cada queso.</li>
    <li>Guarde el día. El inventario de producto terminado se mueve con ese registro.</li>
  </ol>

  <h2>Mermas</h2>
  <p>La merma es la leche o el producto que no llega a venderse: cortesía, vale, faltante o pérdida de proceso. Se anota en el control del día, aparte de los kilos buenos. Así el costo del queso no esconde lo que se fue en el camino. Una merma no se borra en silencio: corregirla es una edición y queda en la bitácora.</p>

  <h2>Catálogo</h2>
  <p>El <strong>Catálogo</strong> muestra el producto terminado con su precio al detal, la foto y si sale en la pantalla de la tienda. El precio se cambia ahí; el alta del producto se hace en producción o inventario. La foto acepta JPG, PNG o WEBP. El cliente ve el precio vigente, no un número escrito a mano en la pizarra.</p>
