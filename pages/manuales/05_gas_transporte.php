  <h1>5. Gas y transporte</h1>
  <p>Estos dos módulos cubren lo que se mueve fuera de la cava: las bombonas de gas de la planta y el flete de quienes llevan el producto.</p>

  <h2>Cilindros de gas</h2>
  <ol>
    <li>En <strong>Gestión de Gas</strong>, pestaña de bombonas, pulse <strong>Bombona</strong>.</li>
    <li>Indique capacidad (10, 15, 27 o 43 kg), estado físico y de quién es.</li>
    <li>Adjunte una foto JPG, PNG o WEBP, de hasta 2 MB. Sirve para no cambiar una bombona por otra en el patio.</li>
    <li>Guarde. El sistema asigna el serial.</li>
  </ol>
  <p>Si cambia la foto, la imagen anterior se borra del servidor y queda la nueva. En la lista se ve la miniatura.</p>
  <p><strong>Eliminar</strong> solo procede si la bombona nunca salió en un viaje ni fue a reparación. Si ya tiene ese historial, no se borra: en <strong>Editar</strong> pásela a <strong>Archivado</strong> para que deje de usarse y los viajes antiguos sigan cuadrando.</p>
  <p>El despacho agrupa las bombonas de un viaje, su costo y los abonos al proveedor. No cargue en un viaje una bombona que está en reparación o en otro despacho sin entregar.</p>

  <h2>Fletes</h2>
  <p>En <strong>Transporte</strong> se registra al transportista, la ruta y el flete del viaje. Al cerrar la semana del transportista, el sistema calcula lo que se le debe. El pago del flete se registra sobre ese cierre y descuenta el saldo. El comprobante queda en la ficha del transportista y el egreso, en caja.</p>
  <p>No reabra una semana ya pagada para cambiar el flete. Si hay un error, anule el pago con el permiso correspondiente y registre el movimiento correcto. La anulación también queda en la bitácora.</p>
