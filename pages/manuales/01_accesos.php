  <h1>1. Introducción y accesos</h1>
  <p>ADARA es el sistema con el que la quesera registra la leche que entra, la convierte en producto, la vende y cobra. Cada persona entra con su propio usuario. Lo que puede ver y modificar depende del permiso que le asignó la administración.</p>

  <h2>Iniciar sesión</h2>
  <ol>
    <li>Abra ADARA en el navegador de la empresa.</li>
    <li>Escriba el correo y la contraseña que le entregaron.</li>
    <li>Pulse <strong>Ingresar</strong>.</li>
  </ol>
  <p>Si los datos no coinciden, el aviso es siempre el mismo. Así nadie puede averiguar qué correos están registrados. Después de varios intentos fallidos, el acceso se pausa unos minutos.</p>

  <h2>Recuperar la contraseña</h2>
  <p>En la pantalla de ingreso, el enlace <strong>¿Olvidaste tu contraseña?</strong> abre el formulario de recuperación.</p>
  <ul>
    <li>Escriba el correo de su cuenta y pulse <strong>Enviar enlace</strong>.</li>
    <li>Si ese correo existe, llega un mensaje con un enlace para crear una clave nueva.</li>
    <li>El enlace dura <strong>15 minutos</strong> y solo puede usarse una vez. Al guardar la clave nueva, el enlace queda anulado.</li>
    <li>La pantalla responde igual aunque el correo no exista. Revise la bandeja y el correo no deseado antes de pedir otro enlace.</li>
  </ul>
  <p>No se puede pedir un enlace nuevo para el mismo correo hasta que pase un minuto. Si el anterior venció, solicite otro.</p>

  <h2>El tablero</h2>
  <p>Después de entrar llega al tablero. El menú de la izquierda abre cada área: productores, control de leche, producción, inventario, ventas, facturas, finanzas, gas y transporte. Arriba se ve la empresa con la que está trabajando.</p>
  <p>Para salir, use <strong>Cerrar sesión</strong>. No deje la sesión abierta en un equipo compartido.</p>
