  <h1>2. Productores y control de leche</h1>
  <p>Cada productor tiene ficha, precio por litro y un día de cierre de su ciclo. La leche se anota el día en que llega. Esa cifra es la base de la liquidación.</p>

  <h2>Registrar la recolección del día</h2>
  <ol>
    <li>Abra <strong>Control de Leche</strong> o la planilla semanal de productores.</li>
    <li>Elija la fecha. No se pueden anotar días futuros.</li>
    <li>Escriba los litros de cada productor y guarde la fila o la semana.</li>
  </ol>
  <p>Si ese productor ya tenía litros en esa fecha, el nuevo número reemplaza al anterior. El precio por litro queda el que tenía el día en que se creó la entrega.</p>

  <h2>Corte de cuenta</h2>
  <p>Cerrar la cuenta de un productor es un corte hasta una fecha, no un candado sobre toda la semana.</p>
  <ul>
    <li>Quedan bloqueados los días <strong>anteriores o iguales</strong> a la fecha del último corte. Esos litros ya entraron en la deuda.</li>
    <li>Los días <strong>posteriores</strong> siguen abiertos. La leche del jueves y del viernes, si el corte fue el miércoles, se anota con normalidad.</li>
    <li>Esos litros nuevos no se suman al corte ya hecho. Pasan solos al siguiente período y salen en la próxima liquidación.</li>
  </ul>
  <p>En la planilla, el candado aparece solo en los días ya cortados. Si una bombona de aviso pide reabrir el ciclo, esa acción es de un administrador y queda registrada.</p>

  <h2>Liquidación</h2>
  <p>La liquidación toma las entregas del período, les aplica el precio congelado de cada día y resta los abonos ya registrados (mercancía, traslado y efectivo). El saldo que queda es lo que la quesera debe al productor. Al pagar, el movimiento entra en caja y el período puede cerrarse para que el arrastre pase al siguiente ciclo.</p>
