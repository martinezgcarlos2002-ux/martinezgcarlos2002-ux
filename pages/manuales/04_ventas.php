  <h1>4. Ventas y finanzas</h1>
  <p>La venta convierte el inventario en una factura y en un cobro. Finanzas muestra si ese dinero ya entró a caja.</p>

  <h2>Factura y ticket</h2>
  <ol>
    <li>Abra <strong>Ventas</strong> o <strong>Control de Facturas</strong>.</li>
    <li>Elija el cliente. Si es nuevo, regístrelo con nombre y documento antes de facturar.</li>
    <li>Cargue los productos, revise el total y emita la factura.</li>
  </ol>
  <p>El ticket se imprime desde la factura. El número no se reutiliza. Anular una factura es una acción aparte y queda registrada; no se edita el total a escondidas.</p>

  <h2>Abono distribuido</h2>
  <p>Cuando el cliente paga una sola suma y tiene varias facturas pendientes, use el abono a varias facturas. ADARA reparte el dinero desde la factura que vence primero. Un abono de 1.000 puede quedar, por ejemplo, en tres facturas.</p>
  <ul>
    <li>Todas las filas de ese pago comparten el mismo identificador de lote.</li>
    <li>Cada fila guarda el <strong>monto original</strong> (los 1.000) y la <strong>tasa del día</strong> en bolívares.</li>
    <li>En el historial de pagos, esas filas muestran la insignia <strong>Pago distribuido</strong> y la tasa aplicada. Así se distingue un solo abono repartido de tres pagos sueltos con la misma referencia.</li>
  </ul>
  <p>Si el abono supera la deuda, el excedente queda como saldo a favor del cliente y se usa en la próxima factura.</p>

  <h2>Estado de cuenta</h2>
  <p>En la ficha del cliente, <strong>Estado de cuenta</strong> reúne facturas, pagos y devoluciones. El saldo es lo emitido menos lo pagado y lo devuelto. Úselo antes de cobrar y al cierre del día, junto con el movimiento de caja en Finanzas.</p>
